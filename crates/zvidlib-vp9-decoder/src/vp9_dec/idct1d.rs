//! The one-dimensional inverse transforms, translated mechanically from
//! libvpx's `vpx_dsp/inv_txfm.c` (BSD-3-Clause; see `THIRD_PARTY_NOTICES.md`)
//! so their intermediate rounding and 16-bit stores match it exactly.

#![allow(unused_assignments, unused_mut, unused_parens, clippy::all)]

const COSPI_1_64: i64 = 16364;
const COSPI_2_64: i64 = 16305;
const COSPI_3_64: i64 = 16207;
const COSPI_4_64: i64 = 16069;
const COSPI_5_64: i64 = 15893;
const COSPI_6_64: i64 = 15679;
const COSPI_7_64: i64 = 15426;
const COSPI_8_64: i64 = 15137;
const COSPI_9_64: i64 = 14811;
const COSPI_10_64: i64 = 14449;
const COSPI_11_64: i64 = 14053;
const COSPI_12_64: i64 = 13623;
const COSPI_13_64: i64 = 13160;
const COSPI_14_64: i64 = 12665;
const COSPI_15_64: i64 = 12140;
const COSPI_16_64: i64 = 11585;
const COSPI_17_64: i64 = 11003;
const COSPI_18_64: i64 = 10394;
const COSPI_19_64: i64 = 9760;
const COSPI_20_64: i64 = 9102;
const COSPI_21_64: i64 = 8423;
const COSPI_22_64: i64 = 7723;
const COSPI_23_64: i64 = 7005;
const COSPI_24_64: i64 = 6270;
const COSPI_25_64: i64 = 5520;
const COSPI_26_64: i64 = 4756;
const COSPI_27_64: i64 = 3981;
const COSPI_28_64: i64 = 3196;
const COSPI_29_64: i64 = 2404;
const COSPI_30_64: i64 = 1606;
const COSPI_31_64: i64 = 804;
const SINPI_1_9: i64 = 5283;
const SINPI_2_9: i64 = 9929;
const SINPI_3_9: i64 = 13377;
const SINPI_4_9: i64 = 15212;

fn wraplow(x: i64) -> i64 {
    x as i32 as i64
}

fn wrap32(x: i64) -> i64 {
    x as i32 as i64
}

fn round_shift(x: i64) -> i64 {
    (x + (1 << 13)) >> 14
}

pub(super) fn idct4(input: &[i32], output: &mut [i32]) {
    let mut step = [0i64; 4];
    let mut temp1: i64;
    let mut temp2: i64;
    temp1 = (((input[0] as i64) as i16 as i64) + ((input[2] as i64) as i16 as i64)) * COSPI_16_64;
    temp2 = (((input[0] as i64) as i16 as i64) - ((input[2] as i64) as i16 as i64)) * COSPI_16_64;
    step[0] = (wraplow(round_shift(temp1))) as i16 as i64;
    step[1] = (wraplow(round_shift(temp2))) as i16 as i64;
    temp1 = ((input[1] as i64) as i16 as i64) * COSPI_24_64
        - ((input[3] as i64) as i16 as i64) * COSPI_8_64;
    temp2 = ((input[1] as i64) as i16 as i64) * COSPI_8_64
        + ((input[3] as i64) as i16 as i64) * COSPI_24_64;
    step[2] = (wraplow(round_shift(temp1))) as i16 as i64;
    step[3] = (wraplow(round_shift(temp2))) as i16 as i64;
    output[0] = (wraplow(step[0] + step[3])) as i32;
    output[1] = (wraplow(step[1] + step[2])) as i32;
    output[2] = (wraplow(step[1] - step[2])) as i32;
    output[3] = (wraplow(step[0] - step[3])) as i32;
}

pub(super) fn iadst4(input: &[i32], output: &mut [i32]) {
    let mut s0: i64;
    let mut s1: i64;
    let mut s2: i64;
    let mut s3: i64;
    let mut s4: i64;
    let mut s5: i64;
    let mut s6: i64;
    let mut s7: i64;
    let mut x0: i64 = (input[0] as i64);
    let mut x1: i64 = (input[1] as i64);
    let mut x2: i64 = (input[2] as i64);
    let mut x3: i64 = (input[3] as i64);
    if (x0 | x1 | x2 | x3) == 0 {
        output.fill(0);
        return;
    }
    s0 = SINPI_1_9 * x0;
    s1 = SINPI_2_9 * x0;
    s2 = SINPI_3_9 * x1;
    s3 = SINPI_4_9 * x2;
    s4 = SINPI_1_9 * x2;
    s5 = SINPI_2_9 * x3;
    s6 = SINPI_4_9 * x3;
    s7 = wraplow(x0 - x2 + x3);
    s0 = s0 + s3 + s5;
    s1 = s1 - s4 - s6;
    s3 = s2;
    s2 = SINPI_3_9 * s7;
    output[0] = (wraplow(round_shift(s0 + s3))) as i32;
    output[1] = (wraplow(round_shift(s1 + s3))) as i32;
    output[2] = (wraplow(round_shift(s2))) as i32;
    output[3] = (wraplow(round_shift(s0 + s1 - s3))) as i32;
}

pub(crate) fn idct8(input: &[i32], output: &mut [i32]) {
    let mut step1 = [0i64; 8];
    let mut step2 = [0i64; 8];
    let mut temp1: i64;
    let mut temp2: i64;
    step1[0] = ((input[0] as i64) as i16 as i64) as i16 as i64;
    step1[2] = ((input[4] as i64) as i16 as i64) as i16 as i64;
    step1[1] = ((input[2] as i64) as i16 as i64) as i16 as i64;
    step1[3] = ((input[6] as i64) as i16 as i64) as i16 as i64;
    temp1 = ((input[1] as i64) as i16 as i64) * COSPI_28_64
        - ((input[7] as i64) as i16 as i64) * COSPI_4_64;
    temp2 = ((input[1] as i64) as i16 as i64) * COSPI_4_64
        + ((input[7] as i64) as i16 as i64) * COSPI_28_64;
    step1[4] = (wraplow(round_shift(temp1))) as i16 as i64;
    step1[7] = (wraplow(round_shift(temp2))) as i16 as i64;
    temp1 = ((input[5] as i64) as i16 as i64) * COSPI_12_64
        - ((input[3] as i64) as i16 as i64) * COSPI_20_64;
    temp2 = ((input[5] as i64) as i16 as i64) * COSPI_20_64
        + ((input[3] as i64) as i16 as i64) * COSPI_12_64;
    step1[5] = (wraplow(round_shift(temp1))) as i16 as i64;
    step1[6] = (wraplow(round_shift(temp2))) as i16 as i64;
    temp1 = (step1[0] + step1[2]) * COSPI_16_64;
    temp2 = (step1[0] - step1[2]) * COSPI_16_64;
    step2[0] = (wraplow(round_shift(temp1))) as i16 as i64;
    step2[1] = (wraplow(round_shift(temp2))) as i16 as i64;
    temp1 = step1[1] * COSPI_24_64 - step1[3] * COSPI_8_64;
    temp2 = step1[1] * COSPI_8_64 + step1[3] * COSPI_24_64;
    step2[2] = (wraplow(round_shift(temp1))) as i16 as i64;
    step2[3] = (wraplow(round_shift(temp2))) as i16 as i64;
    step2[4] = (wraplow(step1[4] + step1[5])) as i16 as i64;
    step2[5] = (wraplow(step1[4] - step1[5])) as i16 as i64;
    step2[6] = (wraplow(-step1[6] + step1[7])) as i16 as i64;
    step2[7] = (wraplow(step1[6] + step1[7])) as i16 as i64;
    step1[0] = (wraplow(step2[0] + step2[3])) as i16 as i64;
    step1[1] = (wraplow(step2[1] + step2[2])) as i16 as i64;
    step1[2] = (wraplow(step2[1] - step2[2])) as i16 as i64;
    step1[3] = (wraplow(step2[0] - step2[3])) as i16 as i64;
    step1[4] = (step2[4]) as i16 as i64;
    temp1 = (step2[6] - step2[5]) * COSPI_16_64;
    temp2 = (step2[5] + step2[6]) * COSPI_16_64;
    step1[5] = (wraplow(round_shift(temp1))) as i16 as i64;
    step1[6] = (wraplow(round_shift(temp2))) as i16 as i64;
    step1[7] = (step2[7]) as i16 as i64;
    output[0] = (wraplow(step1[0] + step1[7])) as i32;
    output[1] = (wraplow(step1[1] + step1[6])) as i32;
    output[2] = (wraplow(step1[2] + step1[5])) as i32;
    output[3] = (wraplow(step1[3] + step1[4])) as i32;
    output[4] = (wraplow(step1[3] - step1[4])) as i32;
    output[5] = (wraplow(step1[2] - step1[5])) as i32;
    output[6] = (wraplow(step1[1] - step1[6])) as i32;
    output[7] = (wraplow(step1[0] - step1[7])) as i32;
}

pub(crate) fn iadst8(input: &[i32], output: &mut [i32]) {
    let mut s0: i64;
    let mut s1: i64;
    let mut s2: i64;
    let mut s3: i64;
    let mut s4: i64;
    let mut s5: i64;
    let mut s6: i64;
    let mut s7: i64;
    let mut x0: i64 = (input[7] as i64);
    let mut x1: i64 = (input[0] as i64);
    let mut x2: i64 = (input[5] as i64);
    let mut x3: i64 = (input[2] as i64);
    let mut x4: i64 = (input[3] as i64);
    let mut x5: i64 = (input[4] as i64);
    let mut x6: i64 = (input[1] as i64);
    let mut x7: i64 = (input[6] as i64);
    if (x0 | x1 | x2 | x3 | x4 | x5 | x6 | x7) == 0 {
        output.fill(0);
        return;
    }
    s0 = (wrap32(COSPI_2_64 * x0 + COSPI_30_64 * x1)) as i32 as i64;
    s1 = (wrap32(COSPI_30_64 * x0 - COSPI_2_64 * x1)) as i32 as i64;
    s2 = (wrap32(COSPI_10_64 * x2 + COSPI_22_64 * x3)) as i32 as i64;
    s3 = (wrap32(COSPI_22_64 * x2 - COSPI_10_64 * x3)) as i32 as i64;
    s4 = (wrap32(COSPI_18_64 * x4 + COSPI_14_64 * x5)) as i32 as i64;
    s5 = (wrap32(COSPI_14_64 * x4 - COSPI_18_64 * x5)) as i32 as i64;
    s6 = (wrap32(COSPI_26_64 * x6 + COSPI_6_64 * x7)) as i32 as i64;
    s7 = (wrap32(COSPI_6_64 * x6 - COSPI_26_64 * x7)) as i32 as i64;
    x0 = wraplow(round_shift(s0 + s4));
    x1 = wraplow(round_shift(s1 + s5));
    x2 = wraplow(round_shift(s2 + s6));
    x3 = wraplow(round_shift(s3 + s7));
    x4 = wraplow(round_shift(s0 - s4));
    x5 = wraplow(round_shift(s1 - s5));
    x6 = wraplow(round_shift(s2 - s6));
    x7 = wraplow(round_shift(s3 - s7));
    s0 = (wrap32(x0)) as i32 as i64;
    s1 = (wrap32(x1)) as i32 as i64;
    s2 = (wrap32(x2)) as i32 as i64;
    s3 = (wrap32(x3)) as i32 as i64;
    s4 = (wrap32(COSPI_8_64 * x4 + COSPI_24_64 * x5)) as i32 as i64;
    s5 = (wrap32(COSPI_24_64 * x4 - COSPI_8_64 * x5)) as i32 as i64;
    s6 = (wrap32(-COSPI_24_64 * x6 + COSPI_8_64 * x7)) as i32 as i64;
    s7 = (wrap32(COSPI_8_64 * x6 + COSPI_24_64 * x7)) as i32 as i64;
    x0 = wraplow(s0 + s2);
    x1 = wraplow(s1 + s3);
    x2 = wraplow(s0 - s2);
    x3 = wraplow(s1 - s3);
    x4 = wraplow(round_shift(s4 + s6));
    x5 = wraplow(round_shift(s5 + s7));
    x6 = wraplow(round_shift(s4 - s6));
    x7 = wraplow(round_shift(s5 - s7));
    s2 = (wrap32(COSPI_16_64 * (x2 + x3))) as i32 as i64;
    s3 = (wrap32(COSPI_16_64 * (x2 - x3))) as i32 as i64;
    s6 = (wrap32(COSPI_16_64 * (x6 + x7))) as i32 as i64;
    s7 = (wrap32(COSPI_16_64 * (x6 - x7))) as i32 as i64;
    x2 = wraplow(round_shift(s2));
    x3 = wraplow(round_shift(s3));
    x6 = wraplow(round_shift(s6));
    x7 = wraplow(round_shift(s7));
    output[0] = (wraplow(x0)) as i32;
    output[1] = (wraplow(-x4)) as i32;
    output[2] = (wraplow(x6)) as i32;
    output[3] = (wraplow(-x2)) as i32;
    output[4] = (wraplow(x3)) as i32;
    output[5] = (wraplow(-x7)) as i32;
    output[6] = (wraplow(x5)) as i32;
    output[7] = (wraplow(-x1)) as i32;
}

