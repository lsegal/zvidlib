//! The one-dimensional inverse transforms of [`crate::vp9_dec`]'s
//! `idct1d`, over vectors of `i32` lanes: each lane runs one independent row
//! or column of a block.
//!
//! This is the scalar file's text with each `i64` value a [`W`], `as i16`
//! truncations spelled [`W::t16`], and the scalar `i32` wraps dropped
//! because every lane is already 32 bits. The all-zero early returns of the
//! ADSTs are dropped too: a zero input transforms to zero either way. The
//! DCTs truncate every stage to 16 bits, so no intermediate can leave `i32`
//! for any input; the ADSTs are only called within the input limits in
//! [`super::transforms`], under which the same holds.

#![allow(unused_assignments, unused_mut, unused_parens, clippy::all)]

