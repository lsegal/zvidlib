    s6 = (wrap32(COSPI_26_64 * x6 + COSPI_6_64 * x7));
    s7 = (wrap32(COSPI_6_64 * x6 - COSPI_26_64 * x7));
    x0 = wraplow(round_shift(s0 + s4));
