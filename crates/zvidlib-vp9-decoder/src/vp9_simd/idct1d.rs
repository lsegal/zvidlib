    let mut x2: W<V> = (input[5]);
    let mut x3: W<V> = (input[2]);
    let mut x4: W<V> = (input[3]);
    let mut x5: W<V> = (input[4]);
    let mut x6: W<V> = (input[1]);
    let mut x7: W<V> = (input[6]);
    s0 = (wrap32(COSPI_2_64 * x0 + COSPI_30_64 * x1));
    s1 = (wrap32(COSPI_30_64 * x0 - COSPI_2_64 * x1));
    s2 = (wrap32(COSPI_10_64 * x2 + COSPI_22_64 * x3));
    s3 = (wrap32(COSPI_22_64 * x2 - COSPI_10_64 * x3));
