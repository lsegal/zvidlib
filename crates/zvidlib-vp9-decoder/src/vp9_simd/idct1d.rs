    x2 = wraplow(round_shift(s2 + s6));
    x3 = wraplow(round_shift(s3 + s7));
    x4 = wraplow(round_shift(s0 - s4));
    x5 = wraplow(round_shift(s1 - s5));
    x6 = wraplow(round_shift(s2 - s6));
    x7 = wraplow(round_shift(s3 - s7));
    s0 = (wrap32(x0));
    s1 = (wrap32(x1));
    s2 = (wrap32(x2));
    s3 = (wrap32(x3));
    s4 = (wrap32(COSPI_8_64 * x4 + COSPI_24_64 * x5));
    s5 = (wrap32(COSPI_24_64 * x4 - COSPI_8_64 * x5));
    s6 = (wrap32(-COSPI_24_64 * x6 + COSPI_8_64 * x7));
    s7 = (wrap32(COSPI_8_64 * x6 + COSPI_24_64 * x7));
    x0 = wraplow(s0 + s2);
    x1 = wraplow(s1 + s3);
    x2 = wraplow(s0 - s2);
    x3 = wraplow(s1 - s3);
    x4 = wraplow(round_shift(s4 + s6));
    x5 = wraplow(round_shift(s5 + s7));
    x6 = wraplow(round_shift(s4 - s6));
    x7 = wraplow(round_shift(s5 - s7));
    s2 = (wrap32(COSPI_16_64 * (x2 + x3)));
    s3 = (wrap32(COSPI_16_64 * (x2 - x3)));
    s6 = (wrap32(COSPI_16_64 * (x6 + x7)));
    s7 = (wrap32(COSPI_16_64 * (x6 - x7)));
    x2 = wraplow(round_shift(s2));
    x3 = wraplow(round_shift(s3));
    x6 = wraplow(round_shift(s6));
    x7 = wraplow(round_shift(s7));
    output[0] = (wraplow(x0));
    output[1] = (wraplow(-x4));
    output[2] = (wraplow(x6));
    output[3] = (wraplow(-x2));
    output[4] = (wraplow(x3));
    output[5] = (wraplow(-x7));
    output[6] = (wraplow(x5));
    output[7] = (wraplow(-x1));
